"""L2 acceptance: GRD <-> slant range against the product's geolocation grid.

Run:
    python tests/test_l2_srgr.py

Truth: every geolocation grid point carries (azimuthTime, pixel, slantRangeTime).
Its ground-range coordinate is gr = pixel*10 m; that coordinate must map to
c*tau/2 and back.  Reference implementation (nearest set) measurements:
    round trip gr->sr->gr : max 0.147 m over gr in [0, 265390], 6 sample times
    grid points, inverse  : max 0.0153 px  (0.153 m)
    grid points, forward  : max 0.000 m (exact — the grid tau is generated by this
                            very polynomial, so 0 slack: right polynomial or bust)
    near edge             : ground_to_slant(0) == sr0 to 0.0 m
Tolerances: round trip < 0.5 m, grid < 0.05 px, forward < 0.01 m, near edge < 1 mm.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import numpy as np

from sargeo import io, srgr

C0 = 299_792_458.0
DX = 10.0
GR_MAX = 265_390.0


def test_near_edge_maps_to_sr0():
    t = io.conversions()[0][len(io.conversions()[0]) // 2]
    c = srgr.conversion(t)
    got = float(srgr.ground_to_slant(0.0, t))
    assert abs(got - c["sr0"]) < 1e-3, f"ground_to_slant(0) = {got:.6f}, sr0 = {c['sr0']:.6f}"


def test_round_trip():
    T, _ = io.conversions()
    gr = np.linspace(0.0, GR_MAX, 20001)
    for t in (T[0], T[5], T[14], T[22], T[-1]):
        back = srgr.slant_to_ground(srgr.ground_to_slant(gr, t), t)
        err = np.abs(back - gr).max()
        assert err < 0.5, f"round trip at t={t:.1f}: max {err:.3f} m"


def test_grid_pixels_inverse():
    G, tg = io.grid()
    sr_true = C0 * G[:, io.TAU] / 2.0
    gr_px = G[:, io.PIXEL] * DX
    worst = 0.0
    for n in range(len(tg)):
        gr = float(srgr.slant_to_ground(sr_true[n], tg[n]))
        worst = max(worst, abs(gr - gr_px[n]))
    px = worst / DX
    assert px < 0.05, f"grid pixel error {px:.4f} px (reference impl: 0.0153 px)"


def test_grid_pixels_forward():
    G, tg = io.grid()
    sr_true = C0 * G[:, io.TAU] / 2.0
    gr_px = G[:, io.PIXEL] * DX
    worst = 0.0
    for n in range(len(tg)):
        sr = float(srgr.ground_to_slant(gr_px[n], tg[n]))
        worst = max(worst, abs(sr - sr_true[n]))
    assert worst < 0.01, f"forward max error {worst:.4f} m (reference impl: 0.0000 m)"


def test_shape_contract():
    t = io.conversions()[0][10]
    a = srgr.ground_to_slant(1000.0, t)
    assert np.ndim(a) == 0, f"scalar in -> {np.ndim(a)}-d out, contract says 0-d"
    b = srgr.ground_to_slant([1000.0, 2000.0], t)
    assert np.shape(b) == (2,), f"list in -> shape {np.shape(b)}"
    c = srgr.slant_to_ground(np.array([800_000.0, 900_000.0]), t)
    assert c.shape == (2,)


if __name__ == "__main__":
    tests = [test_near_edge_maps_to_sr0, test_round_trip, test_grid_pixels_inverse,
             test_grid_pixels_forward, test_shape_contract]
    fails = 0
    for fn in tests:
        try:
            fn()
            print(f"PASS  {fn.__name__}")
        except NotImplementedError as e:
            print(f"RED   {fn.__name__}: {e}")
            fails += 1
        except AssertionError as e:
            print(f"FAIL  {fn.__name__}: {e}")
            fails += 1
        except Exception as e:
            print(f"FAIL  {fn.__name__}: {type(e).__name__}: {e}")
            fails += 1
    print(f"\n{len(tests)-fails}/{len(tests)} green" if fails else "\nAll green~ did you do that on purpose?")
    sys.exit(1 if fails else 0)